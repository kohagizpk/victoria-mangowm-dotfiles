#!/usr/bin/env python3
"""Read Linux DRM outputs without changing hardware state; generate Mango rules.

No display server, sudo, EDID parser or extra Python package is required.
libdrm's read-only connector query supplies the driver's validated mode list.
If access is denied, sysfs supplies names and sizes, leaving refresh to Mango.
"""
import argparse
import ctypes as C
from dataclasses import dataclass
import os
from pathlib import Path
import re
import sys
import tempfile

MARKER = '# Generated by Victoria monitor detection.'
LEGACY_RULES = {
    'monitor_rule=name:^DP-1$,width:1920,height:1080,refresh:165.001999,x:0,y:0',
    'monitor_rule=name:^HDMI-A-1$,width:1920,height:1080,refresh:60,x:1920,y:0',
}


class ModeInfo(C.Structure):
    # Stable libdrm ABI: xf86drmMode.h / drmModeModeInfo.
    _fields_ = [('clock', C.c_uint32)] + [
        (name, C.c_uint16) for name in
        ('hdisplay', 'hsync_start', 'hsync_end', 'htotal', 'hskew',
         'vdisplay', 'vsync_start', 'vsync_end', 'vtotal', 'vscan')
    ] + [(name, C.c_uint32) for name in ('vrefresh', 'flags', 'type')] + [('name', C.c_char * 32)]


class Connector(C.Structure):
    _fields_ = [(name, C.c_uint32) for name in
                ('connector_id', 'encoder_id', 'connector_type', 'connector_type_id')]
    _fields_ += [('connection', C.c_int), ('mmWidth', C.c_uint32), ('mmHeight', C.c_uint32),
                 ('subpixel', C.c_int), ('count_modes', C.c_int), ('modes', C.POINTER(ModeInfo)),
                 ('count_props', C.c_int), ('props', C.POINTER(C.c_uint32)),
                 ('prop_values', C.POINTER(C.c_uint64)), ('count_encoders', C.c_int),
                 ('encoders', C.POINTER(C.c_uint32))]


@dataclass(frozen=True)
class Mode:
    width: int
    height: int
    refresh: float = 0
    preferred: bool = False


def driver_modes(connector, device):
    """GETCONNECTOR only; never acquire DRM master or set a mode."""
    try:
        lib = C.CDLL('libdrm.so.2')
        lib.drmModeGetConnectorCurrent.argtypes = [C.c_int, C.c_uint32]
        lib.drmModeGetConnectorCurrent.restype = C.POINTER(Connector)
        lib.drmModeFreeConnector.argtypes = [C.POINTER(Connector)]
        lib.drmModeFreeConnector.restype = None
        connector_id = int((connector / 'connector_id').read_text())
        fd = os.open(device, os.O_RDONLY | os.O_CLOEXEC)
        try:
            ptr = lib.drmModeGetConnectorCurrent(fd, connector_id)
            if not ptr:
                return []
            try:
                result = []
                if ptr.contents.connection != 1:
                    return result
                for i in range(ptr.contents.count_modes):
                    m = ptr.contents.modes[i]
                    # Avoid interlaced, doublescan and stereoscopic modes.
                    if m.flags & ((1 << 4) | (1 << 5) | (31 << 14)):
                        continue
                    if not (m.htotal and m.vtotal and m.clock):
                        continue
                    hz = m.clock * 1000 / m.htotal / m.vtotal / max(1, m.vscan)
                    if 0 < m.hdisplay < 10000 and 0 < m.vdisplay < 10000 and 1 <= hz < 1000:
                        result.append(Mode(m.hdisplay, m.vdisplay, hz, bool(m.type & (1 << 3))))
                return result
            finally:
                lib.drmModeFreeConnector(ptr)
        finally:
            os.close(fd)
    except (OSError, ValueError, AttributeError):
        return []


def choose_mode(modes):
    """Native/preferred resolution, then highest advertised refresh at that size."""
    preferred = next((m for m in modes if m.preferred), None)
    native = preferred or max(modes, key=lambda m: (m.width * m.height, m.width))
    return max((m for m in modes if (m.width, m.height) == (native.width, native.height)),
               key=lambda m: m.refresh)


def detect(sysfs=Path('/sys/class/drm'), devices=Path('/dev/dri')):
    outputs = []
    for connector in sorted(sysfs.glob('card*-*')):
        match = re.fullmatch(r'(card\d+)-([A-Za-z0-9_-]+)', connector.name)
        if not match:
            continue
        card, name = match.groups()
        try:
            if (connector / 'status').read_text().strip() != 'connected':
                continue
            modes = driver_modes(connector, devices / card)
            if not modes:
                # sysfs modes are ordered by the kernel with preferred modes first.
                # They have no refresh information: do not invent a refresh value.
                for line in (connector / 'modes').read_text().splitlines():
                    size = re.fullmatch(r'(\d+)x(\d+)', line.strip())
                    if size and all(0 < int(v) < 10000 for v in size.groups()):
                        modes = [Mode(*map(int, size.groups()))]
                        break
            if modes:
                outputs.append((name, choose_mode(modes)))
        except OSError:
            continue
    # Two GPUs may export the same connector name. A name-only rule cannot
    # distinguish them, so leave ambiguous outputs to the compositor.
    names = [name for name, _ in outputs]
    duplicates = {name for name in names if names.count(name) > 1}
    if duplicates:
        print('Ambiguous connectors on multiple GPUs; using Mango defaults for: ' +
              ', '.join(sorted(duplicates)), file=sys.stderr)
    return sorted((o for o in outputs if o[0] not in duplicates),
                  key=lambda o: (not o[0].startswith(('eDP-', 'LVDS-', 'DSI-')), o[0]))


def render(outputs):
    lines = [MARKER, '# Personal rules: local/monitor.conf (loaded before this file).',
             '# Side by side from 0,0; scale 1. Only driver-advertised modes.',
             '# Refresh omitted when only sysfs is readable; Mango chooses its preferred mode.']
    x = 0
    for name, mode in outputs:
        rule = f'monitor_rule=name:^{name}$'
        if mode.refresh:
            rule += f',width:{mode.width},height:{mode.height},refresh:{mode.refresh:.6f}'
        # Without trustworthy timings leave the entire mode selection to Mango.
        rule += f',x:{x},y:0,scale:1'
        lines.append(rule)
        x += mode.width
    if not outputs:
        lines.append('# No readable connected outputs; Mango will use its own defaults.')
    return '\n'.join(lines) + '\n'


def legacy_defaults(text):
    rules = {line.strip() for line in text.splitlines() if line.strip() and not line.lstrip().startswith('#')}
    return bool(rules) and rules == LEGACY_RULES


def configure(destination, outputs=None):
    content = render(detect() if outputs is None else outputs)
    # Refuse parent symlinks; replacing the file itself is atomic and safe.
    if any(p.is_symlink() for p in destination.parents):
        raise RuntimeError(f'Refusing directory symlink: {destination.parent}')
    destination.parent.mkdir(parents=True, exist_ok=True)
    if destination.exists() and destination.read_text() == content:
        return
    fd, name = tempfile.mkstemp(prefix='.monitor-', dir=destination.parent)
    try:
        with os.fdopen(fd, 'w') as stream:
            stream.write(content)
        os.chmod(name, 0o644)
        os.replace(name, destination)
    finally:
        Path(name).unlink(missing_ok=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, help='Write generated rules; without this, preview only.')
    args = parser.parse_args()
    outputs = detect()
    content = render(outputs)
    if args.output:
        if args.output.exists() and not args.output.read_text().startswith(MARKER):
            parser.error('Refusing to replace a manually maintained file. Back it up and move its rules to local/monitor.conf first.')
        configure(args.output, outputs)
    print(content, end='')


if __name__ == '__main__':
    try:
        main()
    except (OSError, RuntimeError) as error:
        sys.exit(str(error))
